'use strict';
const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const root = path.resolve(__dirname,'..');
const browser = path.join(root,'public','src','three.vendor.js');
const license = path.join(root,'public','assets','THREE-LICENSE.txt');
const upstream = fs.readFileSync(path.join(root,'node_modules','three','LICENSE'));
const built = esbuild.buildSync({
  stdin: { contents: "export * from 'three';", resolveDir:root, loader:'js' },
  bundle:true, write:false, minify:true, platform:'browser', format:'iife',
  globalName:'THREE', target:['safari16','chrome110','edge110'], legalComments:'inline',
  banner:{js:'// Generated by scripts/build-three.cjs. Three.js license: /assets/THREE-LICENSE.txt.'}
}).outputFiles[0].contents;
if (process.argv.includes('--check')) {
  if (!Buffer.from(built).equals(fs.readFileSync(browser)) || !upstream.equals(fs.readFileSync(license)))
    throw new Error('Pinned WebGL engine or license differs. Run npm run build:three');
} else {
  fs.writeFileSync(browser,built);
  fs.writeFileSync(license,upstream);
}
console.log('Three.js WebGL bundle verified: '+built.byteLength+' bytes');
