(async function () {
  const out = document.getElementById('results');
  const checks = [];
  const ok = (condition, message) => { if (!condition) throw new Error(message); checks.push(message); };
  const rejected = async (promise, message) => { let failed = false; try { await promise; } catch (_) { failed = true; } ok(failed, message); };
  const id = () => crypto.randomUUID();
  const spec = (mode, key) => ({ mode, questionKey: key, question: { prompt: key, options: ['a', 'b'] }, correctId: 'a' });
  const ans = (r, option, attempt = id()) => ({ mode: r.mode, roundId: r.id, attemptId: attempt, expectedAttemptCount: r.attemptCount, optionId: option });
  let a, b;
  try {
    const dbName = 'test-ledger-' + id();
    [a, b] = await Promise.all([TicketLedger.open({dbName}), TicketLedger.open({dbName})]);
    const child = 'child-a', other = 'child-b';
    const pair = await Promise.all([a.getOrCreateRound(child, spec('listen', 'listen:q1')), b.getOrCreateRound(child, spec('listen', 'listen:q2'))]);
    ok(pair[0].round.id === pair[1].round.id && pair[0].round.questionKey === pair[1].round.questionKey, 'two connections share one durable round and question');
    const round = pair[0].round;
    const otherMode = await b.getOrCreateRound(child, spec('word', 'word:q1'));
    ok(otherMode.round.id !== round.id, 'modes retain independent active rounds');
    const attempts = await Promise.allSettled([a.answer(child, ans(round, 'b')), b.answer(child, ans(round, 'b'))]);
    ok(attempts.filter(x => x.status === 'fulfilled').length === 1, 'concurrent wrong answers use attempt-count CAS');
    const afterWrong = await a.get(child);
    ok(afterWrong.rounds[round.id].attemptCount === 1 && afterWrong.stats.wrong === 1 && afterWrong.balance === 0, 'wrong answer recorded once without deduction');
    const retry = afterWrong.rounds[round.id];
    const sameAttempt = ans(retry, 'a');
    const completed = await Promise.all([a.answer(child, sameAttempt), b.answer(child, sameAttempt)]);
    ok(completed.filter(x => x.duplicate).length === 1 && completed.every(x => x.correct && x.awarded), 'same attempt replay is idempotent');
    let state = await a.get(child);
    ok(state.balance === 1 && state.stars === 1 && state.stats.completed === 1 && state.stats.firstAnswered === 1 && state.stats.firstCorrect === 0 && state.stats.retries === 1, 'retry completion and separate stats and ticket are durable');
    await rejected(a.answer(child, {...sameAttempt, optionId:'b'}), 'attempt ID conflict rejected');
    await rejected(a.answer(child, ans(round, 'a')), 'stale answer cannot award again');
    const resumed = await b.getOrCreateRound(child, spec('listen', 'replacement'));
    ok(resumed.round.id === round.id && resumed.round.status === 'completed', 'completed round persists until explicit advance');
    const advanced = await Promise.all([a.advanceRound(child, {...spec('listen', round.questionKey), roundId:round.id}), b.advanceRound(child, {...spec('listen', round.questionKey), roundId:round.id})]);
    ok(advanced[0].round.id === advanced[1].round.id, 'concurrent advances create only one next round');
    let r = advanced[0].round;
    await rejected(a.answer(child, ans(r, 'a', sameAttempt.attemptId)), 'attempt ID cannot be reused in another round');
    await a.answer(child, ans(r, 'a'));
    r = (await a.advanceRound(child, {...spec('listen',round.questionKey),roundId:r.id})).round;
    const limited = await a.answer(child, ans(r, 'a'));
    ok(!limited.awarded && limited.state.balance === 2 && limited.state.stars === 3 && limited.state.transactions.some(x => x.type === 'quiz_repeat_limit'), 'repeat reward bound logged while stars remain separate');
    const reserve1 = id(), reserve2 = id(), reserve3 = id();
    const race = await Promise.allSettled([a.reserveRide(child,{operationId:reserve1,ride:'carousel'}), b.reserveRide(child,{operationId:reserve2,ride:'coaster'}), a.reserveRide(child,{operationId:reserve3,ride:'coaster'})]);
    ok(race.filter(x => x.status === 'fulfilled').length === 2 && race.filter(x => x.status === 'rejected').length === 1, 'concurrent spending never crosses zero');
    const bookings = race.filter(x => x.status === 'fulfilled').map(x => x.value.reservation);
    let booking = bookings[0];
    const replay = await b.reserveRide(child,{operationId:booking.operationId,ride:booking.ride});
    ok(replay.state.balance === 0 && replay.reservation.operationId === booking.operationId, 'reservation replay never charges twice');
    await a.cancelRide(child, booking.operationId); const cancelled = await b.cancelRide(child, booking.operationId);
    ok(cancelled.state.balance === 1 && cancelled.reservation.status === 'refunded', 'cancel refunds exactly once');
    booking = bookings[1];
    const started = await a.startRide(child, booking.operationId);
    const noRefund = await b.cancelRide(child, booking.operationId);
    const finished = await a.completeRide(child, booking.operationId);
    ok(started.reservation.status === 'started' && noRefund.state.balance === 1 && finished.reservation.status === 'completed', 'started ride consumes once and finishes without refund or extra charge');
    const expiryId = id(); await a.reserveRide(child,{operationId:expiryId,ride:'carousel'});
    const clock = Date.now; Date.now = () => clock() + TicketLedger.RESERVATION_MS + 1000;
    const expired = await b.startRide(child,expiryId); Date.now = clock;
    ok(expired.reservation.status === 'refunded' && expired.state.balance === 1, 'expired unstarted reservation recovers atomically and cannot start');
    ok((await a.get(other)).balance === 0 && (await a.get(other)).stars === 0, 'children have isolated balances and stars');
    const exported = await b.exportSnapshot();
    ok(exported.children.length === 2 && exported.children.find(x => x.childId === child).balance === 1, 'backup snapshot includes durable state');
    await rejected(a.reserveRide(child,{operationId:'constructor',ride:'carousel'}), 'unsafe identifier rejected');
    let notices = 0;
    const unsubscribe = b.subscribe(id => { if (id === 'notify-child') { notices++; b.get(id); } });
    await a.getOrCreateRound('notify-child', spec('listen', 'notify:q1'));
    await new Promise(resolve => setTimeout(resolve, 150));
    unsubscribe();
    ok(notices === 1, 'cross-connection update notifies once; reading does not cause a feedback loop');
    const before = (await b.get(child)).balance; a.close();
    await rejected(a.reserveRide(child,{operationId:id(),ride:'carousel'}), 'database failure rejects operation');
    ok((await b.get(child)).balance === before, 'failed transaction leaves durable balance unchanged');
    const reopened = await TicketLedger.open({dbName});
    const persisted = await reopened.get(child);
    ok(persisted.balance === before && persisted.rounds[round.id].status === 'completed', 'reopen preserves balance and completed round');
    reopened.close();
    b.close();
    out.textContent = 'PASS ' + checks.length + '\n' + checks.join('\n'); document.title = 'PASS Ticket ledger';
  } catch (error) {
    if (a) a.close(); if (b) b.close();
    out.textContent = 'FAIL after ' + checks.length + ': ' + (error.stack || error); document.title = 'FAIL Ticket ledger';
  }
})();
